<#
.SYNOPSIS
    Regenerates docs/FUNCTIONS.md from the help inside every function file.
.DESCRIPTION
    Run after adding, removing or syncing functions. CI fails if the file is out of date,
    so the reference on GitHub always matches the code.
.EXAMPLE
    ./tools/Update-FunctionDocs.ps1
.EXAMPLE
    ./tools/Update-FunctionDocs.ps1 -Check    # exit 1 if docs/FUNCTIONS.md is stale
#>
[CmdletBinding()]
param([switch]$Check)

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$fnRoot = Join-Path $root 'Functions'

$rows = foreach ($f in (Get-ChildItem $fnRoot -Filter *.ps1 -Recurse -File | Sort-Object FullName)) {
    if ($f.FullName -match '[\\/](Local|Private)[\\/]' -or $f.BaseName.StartsWith('_')) { continue }
    $head = Get-Content $f.FullName -TotalCount 12
    $alias = ''; $windowsOnly = $false; $upstream = $false
    foreach ($line in $head) {
        if ($line -match '^\s*\W?#\s*Alias(?:es)?(?:\((\w+)\))?\s*:\s*(.+)$') { $alias = $Matches[2].Trim(); $windowsOnly = $Matches[1] -eq 'Windows' }
        if ($line -match '^# Source: jonlabelle') { $upstream = $true }
        if ($line -match '^\s*function\s') { break }
    }
    $ast = [System.Management.Automation.Language.Parser]::ParseFile($f.FullName, [ref]$null, [ref]$null)
    $fn = $ast.FindAll({ param($n) $n -is [System.Management.Automation.Language.FunctionDefinitionAst] }, $false) | Select-Object -First 1
    $help = if ($fn) { $fn.GetHelpContent() } else { $null }
    $synopsis = if ($help -and $help.Synopsis) { ($help.Synopsis -replace '\s+', ' ').Trim() } else { '' }
    $example = ''
    if ($help -and $help.Examples.Count) {
        $example = (($help.Examples[0] -split "`r?`n") | Where-Object { $_.Trim() -and $_ -notmatch '^\s*#' } | Select-Object -First 1)
        if ($example) { $example = $example.Trim() -replace '^PS[^>]*>\s*', '' }
    }
    [PSCustomObject]@{
        Category = $f.Directory.Name
        Name     = $f.BaseName
        Alias    = $(if ($alias) { ($alias -split '[,\s]+' | Where-Object { $_ } | ForEach-Object { "``$_``" }) -join ' ' + $(if ($windowsOnly) { ' (Win)' } else { '' }) } else { '' })
        Synopsis = $synopsis.Replace('|', '\|')
        Example  = $example.Replace('|', '\|')
        From     = $(if ($upstream) { 'jonlabelle' } else { '' })
    }
}

$sb = [Text.StringBuilder]::new()
$null = $sb.AppendLine('# Function reference').AppendLine()
$null = $sb.AppendLine('<!-- Generated by tools/Update-FunctionDocs.ps1 - do not edit by hand. -->').AppendLine()
$null = $sb.AppendLine("$(@($rows).Count) functions. In your shell, ``pf`` shows this list and ``Get-Help <Name> -Full`` shows full help and examples.").AppendLine()
$null = $sb.AppendLine('`(Win)` = alias only exists on Windows, so it doesn''t hide the real tool on macOS/Linux. **J** = from [jonlabelle/pwsh-profile](https://github.com/jonlabelle/pwsh-profile).').AppendLine()

$cats = $rows | Group-Object Category | Sort-Object Name
$null = $sb.AppendLine('**Categories:** ' + (($cats | ForEach-Object { "[$($_.Name)](#$($_.Name.ToLower())) ($($_.Count))" }) -join ' | ')).AppendLine()
foreach ($c in $cats) {
    $null = $sb.AppendLine("## $($c.Name)").AppendLine()
    $null = $sb.AppendLine('| Function | Alias | What it does | Example | |').AppendLine('|---|---|---|---|---|')
    foreach ($r in ($c.Group | Sort-Object Name)) {
        $ex = if ($r.Example) { "``$($r.Example)``" } else { '' }
        $j = if ($r.From) { 'J' } else { '' }
        $null = $sb.AppendLine("| ``$($r.Name)`` | $($r.Alias) | $($r.Synopsis) | $ex | $j |")
    }
    $null = $sb.AppendLine()
}

$out = Join-Path $root 'docs/FUNCTIONS.md'
$text = $sb.ToString().Replace("`r`n", "`n")
if ($Check) {
    $current = if (Test-Path $out) { [IO.File]::ReadAllText($out).Replace("`r`n", "`n") } else { '' }
    if ($current -ne $text) { Write-Error 'docs/FUNCTIONS.md is out of date. Run ./tools/Update-FunctionDocs.ps1 and commit.'; exit 1 }
    Write-Host 'docs/FUNCTIONS.md is up to date.' -ForegroundColor Green
    return
}
$null = New-Item -ItemType Directory -Path (Split-Path $out) -Force
[IO.File]::WriteAllText($out, $text)
Write-Host "Wrote $out ($(@($rows).Count) functions)." -ForegroundColor Green
